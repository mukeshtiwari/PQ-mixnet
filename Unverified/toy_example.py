#!/usr/bin/env python3
"""
toy_example.py -- a worked example of the shuffle proof: 2 ballots, N = 4, a 13-bit prime.

It runs the reference implementation (fp_core.py, mix_proof.py) unchanged over a toy field and prints
every message of one interactive execution as Markdown, recomputing each verifier check with a few
lines of plain arithmetic.

    python3 toy_example.py > docs/TOY_EXAMPLE.md

No security at this size: |F| is about 2^26 and three columns are queried.
The toy field has to be installed before mix_proof is imported, so this file patches fp_core first.
"""
import random
import fp_core

TOY_Q, TOY_2ADIC = 7681, 9                                    # 7681 = 15 * 2^9 + 1, prime, = 1 mod 8
_nr = next(x for x in range(2, 50) if pow(x, (TOY_Q - 1) // 2, TOY_Q) == TOY_Q - 1)
fp_core.Q, fp_core.TWO_ADICITY, fp_core.NR = TOY_Q, TOY_2ADIC, _nr
fp_core.ROOT = pow(_nr, (TOY_Q - 1) >> TOY_2ADIC, TOY_Q)
from fp_core import *                                         # noqa: E402  (after the patch, on purpose)
from mix_proof import *                                       # noqa: E402

class ZeroRandom:
    """Prover randomness of the 'bare' run: every mask, pad and salt is zero."""
    def randrange(self, n): return 0
    def randbytes(self, n): return bytes(n)

def sm(x): x %= Q; return str(x - Q) if x > Q // 2 else str(x)           # small values, centred
def ff(x): return str(x[0]) if x[1] == 0 else f"{x[0]}+{x[1]}t"          # element of F
def fl(v): return "[" + ", ".join(ff(x) for x in v) + "]"
def pl(v): return "[" + ", ".join(str(x) for x in v) + "]"               # polynomial, residues
def tl(v): return "[" + ", ".join(sm(x) for x in v) + "]"                # ternary polynomial
out = []
def P(*lines): out.extend(lines)
def code(*lines): P("```", *lines, "```", "")
def lift(v): return [(x % Q, 0) for x in v]
def cube(x): return fsub(fmul(fmul(x, x), x), x)

# ---------------------------------------------------------------------------------- instance and runs
N, TAU = 4, 2
seed = next(s for s in range(1, 200) if make_instance(TAU, N, s)[3].sigma == [1, 0])
bgv, msgs, inst, wit = make_instance(TAU, N, seed)
par = MixParams(N, TAU, C1=8, C2=128, rate_inv=4, qbits=1)
chal = mix_draw_challenges(par, inst, random.Random(2026))
V = lambda: FixedChallenger(chal)
bare = mix_prove(par, inst, wit, ch=V(), rnd=ZeroRandom())
ok, why = mix_verify(par, inst, bare, V()); assert ok, why

P("# Worked example: shuffle proof for 2 ballots, N = 4, q = 7681", "",
  "Generated by `toy_example.py` from the reference implementation, run unchanged over a toy field. "
  "Every number below is a real message of that run. There is no security at this size.", "",
  "The run is interactive: the verifier's challenges are random values. In the real proof they are hashes "
  "of the transcript. Prover randomness is first set to zero (masks, pads, salts), so the algebra is "
  "visible; section 9 switches the masks on.", "",
  "## 0. Setup", "",
  f"- q = {Q}, p = 2, R_q = Z_q[X]/(X^4 + 1). A polynomial is its coefficient list `[c0, c1, c2, c3]`.",
  f"- F = Z_q[t]/(t^2 - {NR}). An element is written `a+bt`. |F| = q^2 = {Q * Q}.",
  "- Ciphertext c = (u, v) = (a r + 2 e1, b r + 2 e2 + m). Decryption: (v - s u) centred, mod 2.", "")
code(f"secret key  s = {tl(bgv.s)}      (never used by the mix server; shown to check decryption)",
     f"public key  a = {pl(inst.a)}", f"            b = {pl(inst.b)}      = a s + 2 e", "",
     *[f"ballot {i}: m_{i} = {pl(msgs[i])}\n   c_{i} = (u, v),  u = {pl(inst.cin[i][0])}\n                   v = {pl(inst.cin[i][1])}" for i in range(TAU)])
P("**The mix server's secret (the witness).** It re-randomises input i with w_i = (r, e1, e2) and outputs "
  "position j = input sigma(j).", "")
code(f"sigma = {wit.sigma}          (output 0 is input 1, output 1 is input 0)",
     *[f"w_{i}:  r = {tl(wit.r[i])}   e1 = {tl(wit.e1[i])}   e2 = {tl(wit.e2[i])}" for i in range(TAU)], "",
     *[f"output {j}: chat_{j} = c_{wit.sigma[j]} + (a r + 2 e1, b r + 2 e2) with w_{wit.sigma[j]}\n   u = {pl(inst.cout[j][0])}\n   v = {pl(inst.cout[j][1])}\n   decrypts to {pl(bgv.dec(inst.cout[j]))}" for j in range(TAU)])
assert all(list(bgv.dec(inst.cout[j])) == msgs[wit.sigma[j]] for j in range(TAU))
P("The statement is (a, b, c_0, c_1, chat_0, chat_1). The proof must convince a verifier that such sigma and "
  "ternary w_i exist, without revealing them.", "")

# ---------------------------------------------------------------------------------- round 1
Wk = [[row[y] % Q for row in tbl for y in range(N)] for tbl in (wit.r, wit.e1, wit.e2)]
sig = wit.sigma
P("## 1. Round 1: the prover commits the witness", "",
  "Three tables of length 8 (coefficient y of ballot i at index y + 4i) and the table sigma:", "")
code(*[f"W_{nm:<2} = {tl(Wk[k])}" for k, nm in enumerate(("r", "e1", "e2"))], f"sigma = {sig}")
P(f"Each table is one row of a matrix. A row is Reed-Solomon encoded (big matrix: {par.big.C} data symbols + "
  f"{par.big.nq} pads, code length {par.big.n}; small matrix: {par.small.C} + {par.small.nq}, length {par.small.n}) "
  "and the columns are hashed into a Merkle tree. The prover sends two roots:", "")
code(f"root_big = {bare['root_big'].hex()[:16]}...", f"root_s1  = {bare['root_s1'].hex()[:16]}...")

# ---------------------------------------------------------------------------------- projection
rho_u, rho_v = chal["rho_u"], chal["rho_v"]; alpha, beta = chal["ab"]
zpub, zhat, rp = public_projection(inst, rho_u, rho_v)
z = [fsum([zpub[i]] + [fdot_base(rp[k], Wk[k][N * i:N * (i + 1)]) for k in range(3)]) for i in range(TAU)]
h = [fsub(fadd(z[i], fscale(beta, i)), alpha) for i in range(TAU)]
hh = [fsub(fadd(zhat[j], fscale(beta, sig[j])), alpha) for j in range(TAU)]
u, uh = fbatch_inv(h), fbatch_inv(hh)
assert all(zhat[j] == z[sig[j]] for j in range(TAU)) and sorted(h) == sorted(hh) and fsum(u) == fsum(uh)
P("## 2. Challenge: project every ciphertext to one field element", "",
  "The verifier sends rho in F^8 (four coordinates for u, four for v) and alpha, beta in F:", "")
code(f"rho_u = {fl(rho_u)}", f"rho_v = {fl(rho_v)}", f"alpha = {ff(alpha)}    beta = {ff(beta)}")
P("Everyone can compute the projections of the public ciphertexts, and rho' = rho M_pk, the vector that turns "
  "a re-randomiser into its effect on the projection:", "")
code(f"zpub_i = <rho, coeff(c_i)>     = {fl(zpub)}", f"zhat_j = <rho, coeff(chat_j)>  = {fl(zhat)}", "",
     *[f"rho'_{nm:<2} = {fl(rp[k])}" for k, nm in enumerate(("r", "e1", "e2"))])
P("Only the prover can compute the projection of the re-randomised inputs, z_i = zpub_i + <rho', w_i>:", "")
code(f"z = {fl(z)}", "", f"z_0 = zhat_1 and z_1 = zhat_0: the projections of equal ciphertexts are equal.")
P("**Tagged values.** h_i = z_i + beta*i - alpha for the inputs, hhat_j = zhat_j + beta*sigma_j - alpha for the "
  "outputs. The tag beta*i ties each value to an index, so equal multisets force sigma to be a permutation.", "")
code(f"h    = {fl(h)}", f"hhat = {fl(hh)}        the same two values, in the order given by sigma", "",
     f"u    = 1/h    = {fl(u)}", f"uhat = 1/hhat = {fl(uh)}", "",
     f"sum u = {ff(fsum(u))} = sum uhat        <- the log-derivative identity")
P("If the outputs were not a re-randomised permutation of the inputs, the two multisets would differ and the "
  "two sums would differ, except with probability 3/|F| over rho, alpha, beta (Lemma 5 in `docs/SPEC.md`).", "")

# ---------------------------------------------------------------------------------- round 2 and sumcheck A
GA, GB, GC = bare["G"]
tc = chal["tc"]; k1, k2, k3 = chal["kA"]; rhoA = chal["rhoA"][0]
claimA = fadd(fadd(k1, k2), fmul(rhoA, GA))
mA = bare["A"][0]; pA = [mA[0], fsub(claimA, mA[0])] + list(mA[1:])
r = chal["A.r0"][0]; finA = interp(pA, r)
U, Uh, s_, Hd = bare["evalsA"]
Hh = fsub(fadd(mle(zhat, [r]), fmul(beta, s_)), alpha)
fA = fadd(fmul(eq_eval(tc, [r]), fadd(fmul(k1, fmul(U, Hd)), fmul(k2, fmul(Uh, Hh)))), fmul(k3, fsub(U, Uh)))
gvalA = fmul(fsub(finA, fA), finv(rhoA))
assert gvalA == ZERO and [U, Uh, s_, Hd] == [mle(u, [r]), mle(uh, [r]), mle(lift(sig), [r]), mle(h, [r])]
P("## 3. Round 2: the prover commits u and uhat", "",
  "It sends a third root, and the sums G_A, G_B, G_C of its three masking polynomials (zero in this bare run):", "")
code(f"root_s2 = {bare['root_s2'].hex()[:16]}...", f"G = {fl(bare['G'])}")
P("The verifier never sees h, hhat, u or uhat. What remains is to prove three facts about committed tables: "
  "u*h = 1 everywhere, uhat*hhat = 1 everywhere, and sum u = sum uhat.", "",
  "## 4. Sumcheck A: the permutation argument", "",
  "The verifier sends tc (one coordinate, since there are 2 = 2^1 ballots), batching coefficients and rho_A. "
  "(The letter t alone is the generator of F, as in `a+bt`.)", "")
code(f"tc = {ff(tc[0])}    k1 = {ff(k1)}    k2 = {ff(k2)}    k3 = {ff(k3)}    rho_A = {ff(rhoA)}")
P("Claim: the sum over x in {0,1} of  eq(tc,x)(k1 u h + k2 uhat hhat) + k3 (u - uhat) + rho_A g_A  equals "
  "k1 + k2 + rho_A G_A. With u h = 1 the first part sums to k1 + k2, because eq(tc,0) + eq(tc,1) = 1.", "",
  "The prover sends the round polynomial p by its values at 0, 2, 3, 4, 5. The value at 1 is implied:", "")
code(f"claim      = k1 + k2 + rho_A G_A = {ff(claimA)}", f"p(0)       = {ff(pA[0])}", f"p(1)       = claim - p(0) = {ff(pA[1])}",
     f"p(2..5)    = {fl(pA[2:])}", "", f"challenge r = {ff(r)}", f"new claim p(r) = {ff(finA)}      (Lagrange interpolation through the six values)")
P("The prover now sends four evaluations at r. In this bare run they are the multilinear extensions of the "
  "tables, for example U = (1-r) u_0 + r u_1:", "")
code(f"U    = u~(r)     = {ff(U)}", f"Uhat = uhat~(r)  = {ff(Uh)}", f"s    = sigma~(r) = {ff(s_)}", f"Hd   = h~(r)     = {ff(Hd)}")
P("The verifier computes hhat~(r) itself from public data and s, then checks the last sumcheck equation:", "")
code(f"hhat~(r) = zhat~(r) + beta s - alpha = {ff(Hh)}", f"eq(tc,r) = {ff(eq_eval(tc, [r]))}",
     f"eq(tc,r)(k1 U Hd + k2 Uhat hhat~(r)) + k3 (U - Uhat) = {ff(fA)}",
     f"p(r)                                                 = {ff(finA)}      equal: g_A(r) must be {ff(gvalA)}")
P("Four things are now owed: that U, Uhat, s are the committed tables at r (section 7), and that Hd is right. "
  "h is not committed, so Hd needs its own argument.", "")

# ---------------------------------------------------------------------------------- sumcheck B
rhoB = chal["rhoB"][0]
Sp = fadd(fsub(fsub(Hd, mle(zpub, [r])), fmul(beta, r)), alpha)
Wr = [[fadd(fscale(fsub(ONE, r), Wk[k][y]), fscale(r, Wk[k][y + N])) for y in range(N)] for k in range(3)]
summ = [fsum(fmul(rp[k][y], Wr[k][y]) for k in range(3)) for y in range(N)]
assert fsum(summ) == Sp
cl = fadd(Sp, fmul(rhoB, GB)); ry, linesB = [], []
for j, mB in enumerate(bare["B"]):
    p = [mB[0], fsub(cl, mB[0])] + list(mB[1:]); rj = chal[f"B.r{j}"][0]
    linesB.append(f"round {j}: p(0) = {ff(p[0])}   p(1) = {ff(p[1])}   p(2) = {ff(p[2])}   challenge {ff(rj)}   new claim {ff(interp(p, rj))}")
    cl = interp(p, rj); ry.append(rj)
clB = cl
assert clB == fsum(fmul(mle(rp[k], ry), mle(Wr[k], ry)) for k in range(3))
P("## 5. Sumcheck B: h is linear in the committed witness", "",
  "h~(r) = zpub~(r) + beta*r - alpha + sum over the 4 coefficient positions y of sum_k rho'_k(y) W~_k(y, r). "
  "The verifier knows the first three terms, so the claim is about the last one:", "")
code(f"claim = Hd - zpub~(r) - beta r + alpha = {ff(Sp)}", "",
     "W~_k(y, r) = (1-r) W_k[y] + r W_k[y+4]   (the two ballots folded at r)",
     *[f"y = {y}:  sum_k rho'_k(y) W~_k(y, r) = {ff(summ[y])}" for y in range(N)], f"total = {ff(fsum(summ))}      equal to the claim")
P("Two sumcheck rounds over y (rho_B = " + ff(rhoB) + ", unused while g_B = 0):", "")
code(*linesB)
P(f"Final claim of B at r_y = {fl(ry)}:  sum_k rho'_k~(r_y) W~_k(r_y, r) = {ff(clB)}. "
  "The verifier can evaluate rho'_k~(r_y) itself, so this is one linear claim on the committed rows of W.", "")

# ---------------------------------------------------------------------------------- sumcheck C
tz, kC, rhoC = chal["tz"], chal["kC"], chal["rhoC"][0]
cl = fmul(rhoC, GC); rz, linesC = [], []
for j, mC in enumerate(bare["C"]):
    p = [mC[0], fsub(cl, mC[0])] + list(mC[1:]); rj = chal[f"C.r{j}"][0]
    linesC.append(f"round {j}: p(0) = {ff(p[0])}   p(1) = {ff(p[1])}   p(2..) = {fl(p[2:])}\n         challenge {ff(rj)}   new claim {ff(interp(p, rj))}")
    cl = interp(p, rj); rz.append(rj)
wd = bare["evalsC"]
fC = fmul(eq_eval(tz, rz), fsum(fmul(kC[k], cube(wd[k])) for k in range(3)))
assert cl == fC and all(wd[k] == mle(lift(Wk[k]), rz) for k in range(3))
P("## 6. Sumcheck C: the re-randomisers are ternary", "",
  "w^3 - w = 0 exactly when w is -1, 0 or 1. The verifier sends tz in F^3 (the tables have 8 = 2^3 entries) and "
  "coefficients kC; the claim is that the sum over the cube of eq(tz,x) sum_k kC_k (w_k(x)^3 - w_k(x)) is 0.", "")
code(f"tz = {fl(tz)}", f"kC = {fl(kC)}", "", *linesC)
P("In round 0 both p(0) and p(1) are 0, because every table entry is ternary; off the cube the polynomial is "
  "not zero. The prover sends the three evaluations at r_z and the verifier checks the last equation:", "")
code(f"r_z = {fl(rz)}", f"w_k~(r_z) = {fl(wd)}",
     f"eq(tz, r_z) sum_k kC_k (w^3 - w) = {ff(fC)}      equal to the last claim {ff(cl)}")

# ---------------------------------------------------------------------------------- opening
slots, claims = mix_derive(par, inst, bare, V())
names = ["U = u~(r)", "Uhat = uhat~(r)", "s = sigma~(r)", "final claim of B", "w_r~(r_z)", "w_e1~(r_z)", "w_e2~(r_z)", "g_A(r)", "g_C(r_z)"]
mp = par.big; J = chal["pcs.J.big"]; gam = chal["pcs.gamma.big"]; pm = mp.prox_mask
col = [x for b in bare["cols"]["big"][0] for x in b["e"]]; assert len(col) == mp.R
enc = mp.encode_ext(bare["prox"]["big"])
rhs = fadd((col[pm[0]], col[pm[1]]), fsum(fscale(gam[i], col[i]) for i in range(mp.R) if i not in pm))
assert (enc[0][J[0]], enc[1][J[0]]) == rhs
P("## 7. Opening: nine linear claims on committed rows", "",
  "Everything the verifier took on trust is now a linear claim about rows of the two matrices:", "")
code(*[f"{i + 1}. {nm:<18} = {ff(v)}" for i, (nm, (v, _)) in enumerate(zip(names, claims))])
P("One opening proves all nine (spec section 1). The verifier sends kappa (nine coefficients); the prover "
  "sends mu; the verifier sends c and one gamma per row; the prover sends one vector per slot and one "
  "proximity vector per matrix:", "")
code(f"mu = {ff(bare['mu'])}      c = {ff(chal['pcs.c'][0])}",
     *[f"vector {sid} ({slots[sid]['mat']} matrix, {len(v)} entries): {fl(v[:3])[:-1]}, ...]" for sid, v in sorted(bare["vec"].items())],
     *[f"proximity vector, {nm} matrix ({len(v)} entries): {fl(v[:3])[:-1]}, ...]" for nm, v in sorted(bare["prox"].items())])
P("With all masks zero each vector is simply c times a combination of witness rows; with masks on it is "
  "uniformly random. The verifier checks one equation, sum <vector, L> = mu + c V, and then opens columns:", "")
code(f"queried columns: big matrix {J}, small matrix {chal['pcs.J.small']}", "",
     f"column {J[0]} of the big matrix ({mp.R} rows: W_r, W_e1, W_e2 and six mask rows) = {pl(col)}",
     f"encoding of the proximity vector at position {J[0]}          = {ff((enc[0][J[0]], enc[1][J[0]]))}",
     f"mask entries + sum_i gamma_i * column[i]                 = {ff(rhs)}      equal")
P("The same comparison is made for every slot vector and every queried column. A prover whose rows are not "
  "codewords, or whose vectors are not the stated combinations, disagrees on many columns and is caught by a "
  f"random query with constant probability; the real parameters use 190 to 310 queries, here {mp.nq}.", "",
  "## 8. Verdict", "", "`mix_verify` accepts this transcript.", "")

# ---------------------------------------------------------------------------------- masks and simulator
masked = mix_prove(par, inst, wit, ch=V(), rnd=random.Random(7)); assert mix_verify(par, inst, masked, V())[0]
sim = mix_simulate(par, inst, chal, random.Random(9)); assert mix_verify(par, inst, sim, V())[0]
rows = [("G_A", lambda pr: pr["G"][0]), ("first message of A, p(0)", lambda pr: pr["A"][0][0]), ("U", lambda pr: pr["evalsA"][0]),
        ("Uhat", lambda pr: pr["evalsA"][1]), ("s", lambda pr: pr["evalsA"][2]), ("Hd", lambda pr: pr["evalsA"][3]),
        ("w_r~(r_z)", lambda pr: pr["evalsC"][0]), ("mu", lambda pr: pr["mu"])]
P("## 9. The same run with masks, and a run without the witness", "",
  "Same statement, same challenges. Column 2 is the bare run above. Column 3 is the real prover, which adds "
  "a_T Z to every table extension and rho g to every sumcheck. Column 4 is the simulator, which is given "
  "the statement and the challenges but **not** sigma or w.", "",
  "| Message | Bare | Real prover (masked) | Simulator (no witness) |", "| --- | --- | --- | --- |",
  *[f"| {nm} | {ff(f(bare))} | {ff(f(masked))} | {ff(f(sim))} |" for nm, f in rows], "",
  "All three transcripts are accepted. The masked values no longer equal u~(r), sigma~(r) and so on; they are "
  "uniformly random, and the simulator's values have the same distribution. That is the zero-knowledge "
  "property. It is not a forgery: the simulator needs the challenges before it writes its first message, "
  "which the hash-derived challenges of the real proof do not allow.", "")

# ---------------------------------------------------------------------------------- cheating
def out_sum(I):
    zh = public_projection(I, rho_u, rho_v)[1]
    return fsum(fbatch_inv([fsub(fadd(zh[j], fscale(beta, sig[j])), alpha) for j in range(TAU)]))
def attempt(I):
    try: return mix_verify(par, I, mix_prove(par, I, wit, ch=V(), rnd=ZeroRandom()), V())
    except Exception as e: return (False, f"the prover cannot even complete: {type(e).__name__}")
bad1 = Instance(inst.a, inst.b, inst.cin, [(inst.cout[0][0], radd(inst.cout[0][1], [1] + [0] * (N - 1)))] + list(inst.cout[1:]))
bad2 = crt_slot_attack(inst)
rer = [(radd(inst.cin[i][0], t[0]), radd(inst.cin[i][1], t[1])) for i in range(TAU) for t in [bgv.rerand_term(wit.r[i], wit.e1[i], wit.e2[i])]]
ring1 = sum(ring_product_check(bad1, rer, random.Random(k)) for k in range(20))
ring2 = sum(ring_product_check(bad2, rer, random.Random(k)) for k in range(20))
res1, res2 = attempt(bad1), attempt(bad2)
old1, old2 = mix_verify(par, bad1, bare, V()), mix_verify(par, bad2, bare, V())
assert not res1[0] and not res2[0] and not old1[0] and not old2[0]
P("## 10. Two false statements", "",
  "**(a) One plaintext bit of output 0 is flipped.** **(b) The slot attack:** outputs 0 and 1 exchange one of "
  "the four CRT slots of R_q, the attack of Bootle, Lyubashevsky and Merino-Gallardo.", "",
  "| | (a) bit flip | (b) slot swap |", "| --- | --- | --- |",
  f"| Outputs decrypt to | {pl(bgv.dec(bad1.cout[0]))}, {pl(bgv.dec(bad1.cout[1]))} | {pl(bgv.dec(bad2.cout[0]))}, {pl(bgv.dec(bad2.cout[1]))} |",
  f"| Product check over the ring R_q accepts | {ring1} of 20 trials | {ring2} of 20 trials |",
  f"| sum 1/h (inputs) | {ff(fsum(u))} | {ff(fsum(u))} |",
  f"| sum 1/hhat (outputs) | {ff(out_sum(bad1))} | {ff(out_sum(bad2))} |",
  f"| Prover runs on the false statement | rejected: {res1[1]} | rejected: {res2[1]} |",
  f"| Honest proof replayed on the false statement | rejected: {old1[1]} | rejected: {old2[1]} |", "",
  f"The honest outputs decrypt to {pl(msgs[sig[0]])}, {pl(msgs[sig[1]])}. A product check computed in R_q "
  "cannot see the slot swap, because the product is taken slot by slot and each slot still holds the same "
  "two factors. The projection sees it: rho mixes all coefficients of a ciphertext into one field element, "
  "so a ciphertext with one foreign slot projects to a different value, and the two sums differ.", "",
  "Both rejections come at the opening. Sumcheck messages always look consistent, because p(1) is implied by "
  "the claim; a false claim turns into a false evaluation claim (here: g_A(r) is not 0), and the opening "
  "equation exposes it.", "")
print("\n".join(out))
